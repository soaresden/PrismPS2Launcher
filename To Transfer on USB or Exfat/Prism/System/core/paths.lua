--- Index of the media folders. -------------------------------------------------------
--- The manual warns (page 46): checking whether an image exists in a folder of 500
--- items is not the same as looking for it in one of over 1000. Every change of
--- selection asked for up to six different paths, one call to the file system
--- for each, and this fork has multiplied the roots to explore.
--- Here the folder is listed ONCE and after that the check is a table lookup,
--- free. The index is emptied when a list is rebuilt, which is when the
--- content may have changed.
MEDIA_INDICE = {}

function media_indice(directorio)
	local idx = MEDIA_INDICE[directorio]
	if idx ~= nil then return idx end
	idx = {}
	local c = System.listDirectory(directorio)
	if c ~= nil then
		for i = 1, #c do
			if c[i].directory == false then idx[c[i].name] = true end
		end
	end
	MEDIA_INDICE[directorio] = idx
	return idx
end

function media_indice_olvidar()
	MEDIA_INDICE = {}
end

--- Locating covers and screenshots. -------------------------------------------------
--- This fork looks FIRST next to the ROM itself, which lets the media for the
--- games on the exFAT disk live on the exFAT disk:
---   <rom folder>/media/covers/<file without extension>.png
---   <rom folder>/media/screenshots/<file without extension>.png
--- If there is nothing, the program's historic location is used:
---   <launcher>/Multimedia/Covers/Covers <Sistema>/<file without extension>.png
function RUTA_MEDIA(tipo, identidad, sistema, nombre, base)
	if nombre == nil then return "" end
	local carpeta = "covers"
	local clasico = "Covers/Covers "
	if tipo == "screenshot" then
		carpeta = "screenshots"
		clasico = "Screenshots/Screenshots "
	end

	-- 1. "Roms/<alias>/media/..." on each root, IN ORDER: RAICES[1] is always the
	--    boot medium, so the USB wins. A game that lives on the exFAT disk
	--    uses the cover from the USB if it is there, which allows all the images
	--    to be centralised on the stick without duplicating them on the disk.
	if tipo == "cover" then MEDIA_DIAG = {} end
	local function probar(dir, fichero)
		local hay = media_indice(dir)[fichero] == true
		if tipo == "cover" and #MEDIA_DIAG < 8 then
			table.insert(MEDIA_DIAG, (hay and "[ok]   " or "[FALTA] ") .. dir .."/".. fichero)
		end
		return hay
	end

	-- PS1 gathers two formats under the same identity, and their images can be in
	-- the folder of either one. Both are tried.
	local fichero = base ..".png"
	-- PlayStation: ONE single image folder, "Roms/psx/media", as in
	-- EmulationStation. A PS1 game can be a .VCD in "POPS/" or a folder
	-- in "Ember/games/", and it is the same game with the same cover: stored once.
	local alias = {MEDIA_ALIAS[identidad]}
	if RAICES ~= nil then
		for a = 1, #alias do
			if alias[a] ~= nil then
				for i = 1, #RAICES do
					local dir = RAICES[i] .."/Roms/".. alias[a] .."/media/".. carpeta
					if probar(dir, fichero) then return dir .."/".. fichero end
				end
			end
		end
	end

	-- 2. Next to the ROM itself, wherever that may be.
	local orig = nil
	if ORIGEN_DIR ~= nil then orig = ORIGEN_DIR[tostring(identidad) .."|".. nombre] end
	if orig ~= nil then
		local dir = orig .."media/".. carpeta
		if probar(dir, fichero) then return dir .."/".. fichero end
	end

	-- 3. Historic location, for compatibility with existing installations.
	local dir = base_launcher() .."/Multimedia/".. clasico .. sistema
	probar(dir, fichero)
	return dir .."/".. fichero
end

