--- Trace of image loading. ---------------------------------------------------------
--- "Graphics.loadImage" can hang the console with a PNG it does not like or that does
--- not fit in VRAM, and then neither message nor log is left. Here the path is written
--- BEFORE loading it: if the console freezes, the last line of the file names
--- the guilty image. Set to false once it is no longer needed, it writes on every
--- The last image opened, as a witness to a freeze. -----------------------------------
--- If the journal ends on an ART line that says "cargando", the console hung while
--- opening that image: converting or shrinking it settles the case.
--- ART_LOG_ON at false -- which is the normal case -- only keeps it in memory and writes
--- it when something else triggers a dump. At true it writes at once, and then EVERY
--- cover rewrites the whole file: only for hunting down precisely that hang.
ART_LOG_ON = false

function log_art(fase, ruta)
	ART_ULTIMA = tostring(fase) .." -> ".. tostring(ruta)
	if ART_LOG_ON == true then boot_flush() end
end

--- OPL's "ART" folder. It sits at the ROOT of the drive, NOT inside the launcher, and
--- upstream only looked on the boot medium. Here the BDM drives are walked as well,
--- so that "<exFAT disk>/ART" serves the games that live there.
function RUTA_ART(fichero)
	local cand = {}
	local actual = System.currentDirectory()
	local pos = string.find(actual, ":", 1, true)
	if pos ~= nil then table.insert(cand, string.sub(actual, 1, pos)) end
	if BDM_DEVICES ~= nil then
		for i = 1, #BDM_DEVICES do table.insert(cand, BDM_DEVICES[i]) end
	end
	-- OPL's "ART" can hold hundreds of images: it is indexed like the rest.
	for i = 1, #cand do
		if media_indice(cand[i] .."/ART")[fichero] == true then
			return cand[i] .."/ART/".. fichero
		end
	end
	if #cand >= 1 then return cand[1] .."/ART/".. fichero end
	return actual .."/ART/".. fichero
end

--- Global resources (backgrounds, fonts). New location: "Roms/!Prism/",
--- alongside the rest of the content. "Multimedia/Others" is kept as a fallback.
function RUTA_GLOBAL(que)
	local actual = System.currentDirectory()
	local nuevo = actual .."/Roms/!Prism/".. que
	if System.listDirectory(nuevo) ~= nil then return nuevo end
	return actual .."/Multimedia/Others/".. que
end

--- Launcher folder (boot medium). ---------------------------------------------------
function base_launcher()
	return System.currentDirectory()
end

ERROR_DETALLE = nil   -- detail of the last "existe()" failure

--- The error box has only ONE line between the title and the footer. Here a short
--- text is returned (file names only, truncated if need be) and the full version,
--- with the path, is dumped to the journal.
function detalle_falta(etiqueta, base, faltan)
	if faltan == nil or #faltan == 0 then
		log_lanzamiento(etiqueta .."  check failed", {"directory : ".. tostring(base), "(no file identified as missing)"})
		return "Check ".. etiqueta ..": path?"
	end

	local campos = {"expected directory : ".. tostring(base), ""}
	for i = 1, #faltan do
		table.insert(campos, "MISSING : ".. faltan[i])
	end
	log_lanzamiento(etiqueta .."  missing files", campos)

	local corto = "Missing: ".. faltan[1]
	if #faltan >= 2 then corto = corto .." +".. (#faltan-1) end
	if string.len(corto) > 44 then corto = string.sub(corto, 1, 41) .."..." end
	return corto
end
